export type StringKey = keyof typeof STRINGS.en;

/** Traduit une cle ; "{n}" est remplace, et "a|b" choisit le pluriel selon n (> 1). */
export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let s: string = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (s.includes('|')) {
    const n = Number(vars?.n ?? 0);
    const [one, many] = s.split('|');
    // Francais : singulier pour 0 et 1 ; anglais : singulier pour 1 seulement.
    s = (lang === 'fr' ? n > 1 : n !== 1) ? many : one;
  }
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export const LangContext = createContext<Lang>('en');
export const useLang = (): Lang => useContext(LangContext);
export function useT(): (key: StringKey, vars?: Record<string, string | number>) => string {
  const lang = useLang();
  return (key, vars) => translate(lang, key, vars);
}

export function glosses(w: Word, lang: Lang): string[] {
  if (lang === 'en' && w.en?.length) return w.en;
  return w.fr;
}
export function noteOf(w: Word, lang: Lang): string | undefined {
  return lang === 'en' ? (w.noteEn ?? w.note) : w.note;
}
export function exampleText(w: Word, lang: Lang): string | undefined {
  if (!w.example) return undefined;
  return lang === 'en' ? (w.example.en ?? w.example.fr) : w.example.fr;
}
export function posLabel(pos: string, lang: Lang): string {
  return lang === 'en' ? (POS_EN[pos] ?? pos) : pos;
}
export function themeLabel(t: ThemeInfo, lang: Lang): string {
  return lang === 'en' ? (t.labelEn || t.label) : t.label;
}
